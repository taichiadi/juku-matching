async function run() {
  const CHUNK_SIZE = 20;
  let totalInserted = 0;
  let totalErrors = 0;

  for (let i = 0; i < records.length; i += CHUNK_SIZE) {
    const chunk = records.slice(i, i + CHUNK_SIZE);
    const { data, error } = await supabase
      .from("experiences")
      .insert(chunk)
      .select("id");

    if (error) {
      console.error(`Chunk ${i / CHUNK_SIZE + 1} error:`, error.message);
      totalErrors += chunk.length;
    } else {
      totalInserted += data.length;
      console.log(`Chunk ${i / CHUNK_SIZE + 1}: inserted ${data.length} records`);
    }
  }

  console.log(`\n✓ Total inserted: ${totalInserted}, Errors: ${totalErrors}`);

  const { count } = await supabase
    .from("experiences")
    .select("id", { count: "exact", head: true })
    .eq("tutor_verification_status", "sample");
  console.log(`Total sample records in DB: ${count}`);
}

