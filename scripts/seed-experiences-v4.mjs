async function seed() {
  const CHUNK_SIZE = 20;
  let total = 0;
  for (let i = 0; i < SAMPLES.length; i += CHUNK_SIZE) {
    const chunk = SAMPLES.slice(i, i + CHUNK_SIZE);
    const { data, error } = await supabase.from("experiences").insert(chunk).select("id");
    if (error) {
      console.error(`Error at chunk ${i}: ${error.message}`);
    } else {
      total += data.length;
      console.log(`✓ Chunk ${i / CHUNK_SIZE + 1}: inserted ${data.length} records (total: ${total})`);
    }
  }
  console.log(`\nDone: ${total} / ${SAMPLES.length} records inserted`);
}

